"""Assemble BENCHMARKS.md and web/data/planners.json from the result files.

    python -m bench.make_benchmarks

Reads results/{ablation.json, planners_*.json, e2e.json, grounding.json, maniskill.json}
(whichever exist) so the document can never disagree with the data.
"""

import glob
import json
import os
import platform
import subprocess

from bench.report import build, markdown


def _load(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def _gpu():
    try:
        out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"],
                             capture_output=True, text=True, timeout=10).stdout.strip()
        return out or "none detected"
    except Exception:
        return "none detected"


def _versions():
    import mujoco
    import numpy
    return f"Python {platform.python_version()}, MuJoCo {mujoco.__version__}, NumPy {numpy.__version__}"


def planner_section(planners):
    if not planners:
        return "_Not run._\n"
    rows = ["| Model | Valid JSON | Plan accuracy (18 cases) | Median latency |", "|---|---|---|---|"]
    for r in planners:
        rows.append(f"| `{r['model']}` | {100 * r['valid_json']:.0f}% | {100 * r['plan_accuracy']:.0f}% | "
                    f"{r['median_latency_s']:.2f} s |")
    return "\n".join(rows) + "\n"


def e2e_section(e2e):
    if not e2e:
        return "_Not run._\n"
    rows = ["| Planner | Fault profile | Valid LLM plans | No verifier | Verifier + corrected retry |",
            "|---|---|---|---|---|"]
    for r in e2e:
        a, b = r["arms"]["no_verifier"], r["arms"]["verifier_corrected"]
        rows.append(f"| `{r['model']}` | {r['profile']} | {100 * r['llm_valid_rate']:.0f}% | "
                    f"{a['k']}/{a['n']} ({100 * a['rate']:.0f}%) | {b['k']}/{b['n']} ({100 * b['rate']:.0f}%) |")
    return "\n".join(rows) + "\n"


def grounding_section(g):
    if not g:
        return "_Not run._\n"
    rows = ["| Estimator | Detected | Median 3-D error | Within 10 mm | Median latency / frame |", "|---|---|---|---|---|"]
    for name, v in g.items():
        rows.append(f"| `{name}` | {100 * v['detect_rate']:.0f}% | {v['median_err_mm']:.1f} mm | "
                    f"{100 * v['frac_within_10mm']:.0f}% | {v['median_latency_s']:.2f} s |")
    return "\n".join(rows) + "\n"


def maniskill_section(m):
    if not m:
        return "_Not run in this checkout. See docs/DECISIONS.md and `maniskill_bench/`._\n"
    L = [f"`{m['env']}` in the `docker/maniskill` image (CPU simulation, software Vulkan rendering), {m['episodes']} seeds per cell, "
         f"attempt budget {m['attempt_budget']}, the environment's own `success` metric. The cube is localised from the RGB-D camera "
         "(red colour mask + depth, about 2 mm error in the probe); ManiSkill's mplib motion planner executes; the same fault profiles "
         "(grasp/release noise, constant release bias) are injected. The goal position is the task specification.", "",
         "| Fault profile | No verifier | Verifier + blind retry | Verifier + corrected retry |", "|---|---|---|---|"]
    for prof, s in m["summary"].items():
        cells = []
        for arm in ("no_verifier", "verifier_blind", "verifier_corrected"):
            a = s["arms"].get(arm)
            cells.append(f"{a['k']}/{a['n']} = {100 * a['rate']:.0f}% [{100 * a['lo']:.0f}-{100 * a['hi']:.0f}], "
                         f"{a['false_success']} false-ok" if a else "-")
        L.append(f"| {prof} | " + " | ".join(cells) + " |")
    L += ["", "Paired exact McNemar (episodes only the first arm solved vs only the second):", ""]
    for prof, s in m["summary"].items():
        for k, v in s["paired"].items():
            L.append(f"- {prof}, {k.replace('_vs_', ' vs ')}: {v['only_first']} vs {v['only_second']} (p={v['p']:.3g})")
    L += ["", "**Honest limitation.** With no faults the camera-verifier arms lose 2-3 of 30 episodes that the no-verifier arm wins. "
          "The cause is occlusion: PickCube holds the cube in the air at the goal, the gripper hides it from the fixed camera, and the "
          "verifier reports \"cube not visible\" (a false reject) and retries. The MuJoCo study avoids this by moving the arm out of view "
          "before each look; this task cannot. Noisy-profile gains (27% to 40%) are not statistically significant at n=30.", ""]
    return "\n".join(L)


def main():
    ablation = _load("results/ablation.json")
    planners = []
    for path in sorted(glob.glob("results/planners_*.json")):
        planners += _load(path) or []
    e2e, grounding, mani = _load("results/e2e.json"), _load("results/grounding.json"), _load("results/maniskill.json")

    doc = ["# Benchmarks", "",
           "Generated by `python -m bench.make_benchmarks` from the files in `results/`. Nothing here is typed by hand.", "",
           "## Hardware and software", "",
           f"- {platform.platform()}", f"- GPU: {_gpu()}", f"- {_versions()}",
           "- Local models: Ollama, Qwen3-VL (GGUF, Q4) at the sizes named below.", "",
           "## 1. Verifier ablation (MuJoCo, the main result)", "",
           "**Question.** When execution can fail, how much does verifying from camera pixels raise task success, and how much more does feeding the measured error back into the retry add?", "",
           "**Design.** Three tasks (pick-and-place, stack, two-step) on seeded random scenes; four fault profiles injected into the arm "
           "(`env/faults.py`); five arms sharing identical attempt-1 faults per seed; attempt budget 3; success scored by simulator ground truth "
           "at episode end. Comparisons are paired by seed (exact McNemar). Reproduce: `python -m bench.run --episodes 30`, then `python -m bench.report`.", ""]
    doc.append(markdown(build(ablation)) if ablation else "_Not run._")
    doc += ["", "Notes: *attempts* count every attempt of every subtask in an episode, so the two-step task contributes at least 2. "
            "*false-ok* is an episode the robot reported as successful that ground truth scored as a failure.", "",
            "## 2. Local planner models", "",
            "18 hand-labelled instructions (synonyms, multi-step, \"all blocks\", two ambiguous ones that should trigger a clarification). "
            "`heuristic` is the regex fallback parser. A model row counts a case as correct only if the LLM answered with valid JSON; "
            "`-instruct` tags are Qwen3-VL's non-thinking variants, the untagged ones think before answering.", "",
            planner_section(planners),
            "### End to end, per planner", "",
            "Instruction -> plan -> closed loop -> ground-truth score; 10 seeds x 3 tasks per cell; plans are generated once per model and reused across the two arms.", "",
            e2e_section(e2e),
            "Every planner scores identically here: the benchmark's instructions are regular enough that even the regex parser plans them "
            "perfectly, so end-to-end success is decided by the verifier arm, not the planner. Planner quality shows only in the 18-case table above.", "",
            "## 3. Perception: segmentation vs VLM grounding", "",
            "Same RGB-D frame to each estimator; error is the 3-D distance to the simulator's true block centre.", "",
            grounding_section(grounding),
            "## 4. ManiSkill3 (standard benchmark)", "",
            maniskill_section(mani)]
    with open("BENCHMARKS.md", "w", encoding="utf-8") as f:
        f.write("\n".join(doc))

    os.makedirs("web/data", exist_ok=True)
    with open("web/data/planners.json", "w", encoding="utf-8") as f:
        json.dump({"planner_eval": [{k: v for k, v in p.items() if k != "cases"} for p in planners],
                   "end_to_end": e2e or []}, f)
    if mani:
        with open("web/data/maniskill.json", "w", encoding="utf-8") as f:
            json.dump({k: mani[k] for k in ("env", "episodes", "attempt_budget", "summary")}, f)
    print("wrote BENCHMARKS.md and web/data/planners.json")


if __name__ == "__main__":
    main()
